/// Looks up the row bytes for [character], or null when the font has no
/// glyph for it (the caller draws a blank advance instead).
List<int>? glyphFor(String character) {
  if (character.isEmpty) return null;
  return _glyphs[character.toUpperCase()];
}

/// True when every character in [text] has a glyph, so a HUD string will
/// not silently lose characters.
bool canRender(String text) {
  for (final rune in text.runes) {
    final char = String.fromCharCode(rune);
    if (char == ' ') continue;
    if (_glyphs[char.toUpperCase()] == null) return false;
  }
  return true;
}
